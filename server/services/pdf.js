import PDFDocument from 'pdfkit';
import path from 'path';
import fs from 'fs';
import { fileURLToPath } from 'url';
import logger from '../lib/logger.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PDF_DIR = path.join(__dirname, '..', '..', 'data', 'pdfs');

if (!fs.existsSync(PDF_DIR)) fs.mkdirSync(PDF_DIR, { recursive: true });

function createDoc(filename) {
  const filePath = path.join(PDF_DIR, filename);
  const doc = new PDFDocument({ margin: 50, size: 'A4' });
  const stream = fs.createWriteStream(filePath);
  doc.pipe(stream);
  doc.on('error', err => stream.destroy(err));
  stream.on('error', err => { throw err; });
  return { doc, filePath, filename, stream };
}

function finalizeDoc({ doc, stream, filePath, filename }) {
  return new Promise((resolve, reject) => {
    stream.on('finish', () => {
      logger.info({ filename }, 'PDF generated');
      resolve({ filePath, filename });
    });
    stream.on('error', reject);
    doc.end();
  });
}

function header(doc, title) {
  doc.fontSize(22).font('Helvetica-Bold').text('Marvelops TravelPro', { align: 'center' });
  doc.moveDown(0.5);
  doc.fontSize(10).font('Helvetica').fillColor('#64748b').text(title, { align: 'center' });
  doc.moveDown(1);
  doc.strokeColor('#2563eb').lineWidth(2).moveTo(50, doc.y).lineTo(545, doc.y).stroke();
  doc.moveDown(1);
  doc.fillColor('#1a1a2e').fontSize(12).font('Helvetica');
}

function footer(doc) {
  doc.fontSize(8).fillColor('#94a3b8').text(
    `Generated by Marvelops TravelPro — ${new Date().toLocaleDateString()}`,
    50, doc.page.height - 50, { align: 'center', width: 500 }
  );
}

export async function generateBookingConfirmation({ clientName, reference, destination, dates, details } = {}) {
  const filename = `booking_${reference || 'draft'}_${Date.now()}.pdf`;
  const ctx = createDoc(filename);
  const { doc } = ctx;

  header(doc, 'Booking Confirmation');

  doc.fontSize(14).font('Helvetica-Bold').fillColor('#059669').text('✓ Booking Confirmed', { align: 'center' });
  doc.moveDown(1.5);

  const items = [
    ['Reference', reference],
    ['Client', clientName],
    ['Destination', destination],
    ['Dates', dates],
    ['Details', details],
  ];

  doc.fontSize(11).font('Helvetica');
  for (const [label, value] of items) {
    if (!value) continue;
    doc.fillColor('#64748b').font('Helvetica-Bold').text(`${label}:`, { continued: true });
    doc.fillColor('#1a1a2e').font('Helvetica').text(`  ${value}`);
    doc.moveDown(0.3);
  }

  footer(doc);
  return finalizeDoc(ctx);
}

